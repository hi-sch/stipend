function copy(base, over) {
  const out = structuredClone(base)
  function merge(a, b) {
    for (const k of Object.keys(b)) {
      if (b[k] && typeof b[k] === 'object' && !Array.isArray(b[k])) merge(a[k] || (a[k] = {}), b[k])
      else a[k] = b[k]
    }
  }
  merge(out, over)
  return out
}

